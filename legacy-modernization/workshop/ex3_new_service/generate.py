"""Exercise 3: generate the new service with an LLM from the *rules*, not from the COBOL.

The model sees the rule list (from ex2, or the verified answer key) and the domain contract and must
write `post_interest(...)` in plain Python. It never sees the COBOL source, so whatever it gets right
comes from the specification. Exercise 4 then proves (or disproves) equivalence against the legacy run.

Usage:
  python ex3_new_service/generate.py                  # spec = gold_rules.json (verified answer key)
  python ex3_new_service/generate.py --rules out/rules.json   # spec = what the LLM extracted in ex2
  python ex3_new_service/generate.py --from-cobol --out out/candidate_cobol.py   # "LLM-only" baseline:
                                                   # the model reads the COBOL itself, no rule list
Then: python ex4_equivalence/diamond.py --impl out/candidate_llm.py
"""
from __future__ import annotations

import argparse
import ast
import json
import pathlib
import sys
import time

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from common.llm import chat, extract_code  # noqa: E402
from common.paths import OUT, WORKSHOP  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent

PROMPT = """You are modernizing a mainframe batch job into a Python service.
Implement the function `post_interest` described by the CONTRACT, following the BUSINESS RULES exactly.
Preserve legacy behaviour bug-for-bug unless a rule says otherwise: the new code will be tested byte-for-byte
against the running legacy program. Use decimal.Decimal for money. Do not round where the rules say truncate.

Requirements:
- Output ONE ```python code block containing a complete module. No explanations.
- First line of code: `from ex3_new_service.contract import Account, CategoryBalance, InterestResult, InterestTransaction, JobAbend`
- Signature: def post_interest(accounts, card_by_account, rates, balances, run_date, legacy_compat=True) -> InterestResult
- Do not mutate the input `accounts` dict in place: deep-copy it.
- Raise JobAbend(999, reason) wherever the legacy job would abend.
- tran_id is 16 chars, cat_cd values are 4-digit strings like "0005", type_cd 2-char strings like "01".

CONTRACT:
{contract}

BUSINESS RULES:
{rules}
"""


def load_rules(path: str | None) -> list[dict]:
    if path:
        data = json.loads(pathlib.Path(path).read_text())
        return [{"id": r.get("id"), "rule": r.get("description") or r.get("title")} for r in data["rules"]]
    gold = json.loads((WORKSHOP / "ex2_rule_extraction" / "gold_rules.json").read_text())
    return [{"id": r["id"], "rule": r["text"]} for r in gold["rules"]]


COBOL_PROMPT = """You are modernizing a mainframe batch job into a Python service.
Read the COBOL program and copybooks below and implement the function `post_interest` described by the CONTRACT
so that it behaves exactly like the COBOL program (it will be tested byte-for-byte against the running program).
Use decimal.Decimal for money.

Requirements:
- Output ONE ```python code block containing a complete module. No explanations.
- First line of code: `from ex3_new_service.contract import Account, CategoryBalance, InterestResult, InterestTransaction, JobAbend`
- Signature: def post_interest(accounts, card_by_account, rates, balances, run_date, legacy_compat=True) -> InterestResult
- Do not mutate the input `accounts` dict in place: deep-copy it.
- Raise JobAbend(999, reason) wherever the legacy job would abend.

CONTRACT:
{contract}

COBOL PROGRAM CBACT04C:
{program}

COPYBOOKS:
{copybooks}
"""


def validate(text: str):
    code = extract_code(text)
    tree = ast.parse(code)  # syntax check
    if not any(isinstance(n, ast.FunctionDef) and n.name == "post_interest" for n in tree.body):
        raise ValueError("no post_interest() in generated module")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rules", help="rules JSON from ex2 (default: verified answer key)")
    ap.add_argument("--from-cobol", action="store_true", help="baseline: give the model the COBOL, not the rules")
    ap.add_argument("--out", default=str(OUT / "candidate_llm.py"))
    a = ap.parse_args()
    contract = (HERE / "contract.py").read_text()
    if a.from_cobol:
        from common.paths import CBACT04C
        from ex2_rule_extraction.extract import copybooks
        prompt = COBOL_PROMPT.format(contract=contract, program=CBACT04C.read_text(encoding="latin-1"),
                                     copybooks=copybooks())
        a.rules = "COBOL source (no rules)"
    else:
        prompt = PROMPT.format(contract=contract, rules=json.dumps(load_rules(a.rules), indent=1))
    t0 = time.time()
    text, model = chat([{"role": "user", "content": prompt}], max_tokens=8000, validate=validate)
    code = f"# generated by {model} from {a.rules or 'gold_rules.json'} in {time.time() - t0:.0f}s\n" + extract_code(text)
    pathlib.Path(a.out).write_text(code)
    print(f"{model}: {len(code.splitlines())} lines in {time.time() - t0:.0f}s -> {a.out}")
    print(f"next: python ex4_equivalence/diamond.py --impl {a.out}")


if __name__ == "__main__":
    main()
